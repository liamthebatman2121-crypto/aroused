import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, readFile, rm } from 'node:fs/promises';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { DatabaseSync } from 'node:sqlite';
import os from 'node:os';

const root = path.resolve(import.meta.dirname, '..');
const sqlitePath = path.join(root, 'migration-backups', 'schema-probe-verified', 'data', 'aroused.sqlite');
const schemaPath = path.join(root, 'migrations', 'postgres', '001_schema.sql');

test('generated PostgreSQL schema covers every table and preserves critical constraints', async () => {
  const sqlite = new DatabaseSync(sqlitePath, { readOnly: true });
  const tableNames = sqlite.prepare("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name").all().map(row => row.name);
  const schema = await readFile(schemaPath, 'utf8');
  for (const name of tableNames) assert.match(schema, new RegExp(`CREATE TABLE ${name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\s*\\(`), `missing PostgreSQL table ${name}`);
  assert.match(schema, /GENERATED BY DEFAULT AS IDENTITY/);
  assert.match(schema, /REFERENCES users\(id\) ON DELETE CASCADE/);
  assert.match(schema, /users_email_ci_uq ON users \(lower\(email\)\)/);
  assert.match(schema, /users_username_ci_uq ON users \(lower\(username\)\)/);
  assert.match(schema, /CREATE UNIQUE INDEX .*album_media.*storage_name|storage_name TEXT NOT NULL UNIQUE/);
  assert.match(schema, /UNIQUE\(album_id,position\)/);
  assert.equal(tableNames.length, 31);
  sqlite.close();
});

test('staging importer requires an explicit staging confirmation and never defaults to a runtime switch', async () => {
  const missingDsn = spawnSync(process.execPath, ['scripts/postgres/migrate-staging.mjs', sqlitePath], { cwd: root, encoding: 'utf8', env: { ...process.env, AROUSED_STAGING_DATABASE_URL: '', AROUSED_ALLOW_STAGING_POSTGRES_MIGRATION: '' } });
  assert.notEqual(missingDsn.status, 0);
  assert.match(missingDsn.stderr, /AROUSED_STAGING_DATABASE_URL/);
  const unmarked = spawnSync(process.execPath, ['scripts/postgres/migrate-staging.mjs', sqlitePath], { cwd: root, encoding: 'utf8', env: { ...process.env, AROUSED_STAGING_DATABASE_URL: 'postgresql://not-used', AROUSED_STAGING_DATABASE_NAME: 'aroused_prod', AROUSED_STAGING_DATABASE_DISPOSABLE: 'YES', AROUSED_ALLOW_STAGING_POSTGRES_MIGRATION: 'YES' } });
  assert.notEqual(unmarked.status, 0);
  assert.match(unmarked.stderr, /ending in _staging or _test/);
  const noMarkerApproval = spawnSync(process.execPath, ['scripts/postgres/migrate-staging.mjs', sqlitePath], { cwd: root, encoding: 'utf8', env: { ...process.env, AROUSED_STAGING_DATABASE_URL: 'postgresql://not-used', AROUSED_STAGING_DATABASE_NAME: 'aroused_staging', AROUSED_STAGING_DATABASE_ROLE: 'aroused_staging_migrator', AROUSED_STAGING_DATABASE_DISPOSABLE: '', AROUSED_ALLOW_STAGING_POSTGRES_MIGRATION: 'YES' } });
  assert.notEqual(noMarkerApproval.status, 0);
  assert.match(noMarkerApproval.stderr, /AROUSED_STAGING_DATABASE_DISPOSABLE/);
  const importer = await readFile(path.join(root, 'scripts/postgres/migrate-staging.mjs'), 'utf8');
  assert.ok(importer.indexOf('current_database()') < importer.indexOf("await client.query('BEGIN')"));
  assert.match(importer, /aroused-disposable-staging/);
  assert.match(importer, /missing after schema creation/);
  assert.match(importer, /foreign-key constraints missing or mismatched/);
  assert.match(importer, /dedicated database owner/);
  assert.match(importer, /Target public schema contains database objects/);
  assert.doesNotMatch(await readFile(path.join(root, 'server.mjs'), 'utf8'), /AROUSED_STAGING_DATABASE_URL/);
});

test('PostgreSQL staging data import preserves row counts and relationships', {
  skip: !process.env.AROUSED_TEST_POSTGRES_URL || !process.env.AROUSED_TEST_POSTGRES_DATABASE_NAME || !process.env.AROUSED_TEST_POSTGRES_DATABASE_ROLE ? 'Set AROUSED_TEST_POSTGRES_URL, AROUSED_TEST_POSTGRES_DATABASE_NAME, and AROUSED_TEST_POSTGRES_DATABASE_ROLE to a marked, empty disposable PostgreSQL test database and install pg.' : false,
}, async () => {
  const scratch = await mkdtemp(path.join(os.tmpdir(), 'aroused-pg-migration-'));
  const fixturePath = path.join(scratch, 'migration-source.sqlite');
  const base = new DatabaseSync(sqlitePath);
  base.exec(`VACUUM INTO '${fixturePath.replaceAll("'", "''")}'`);
  base.close();
  const fixture = new DatabaseSync(fixturePath);
  fixture.exec('PRAGMA foreign_keys=ON');
  const userId = Number(fixture.prepare('SELECT COALESCE(MAX(id),0)+101 AS id FROM users').get().id);
  const storyId = Number(fixture.prepare('SELECT COALESCE(MAX(id),0)+101 AS id FROM stories').get().id);
  const albumId = Number(fixture.prepare('SELECT COALESCE(MAX(id),0)+101 AS id FROM albums').get().id);
  const mediaId = Number(fixture.prepare('SELECT COALESCE(MAX(id),0)+101 AS id FROM album_media').get().id);
  const now = new Date().toISOString();
  fixture.prepare('INSERT INTO users(id,display_name,email,avatar_initial,created_at,username,bio) VALUES(?,?,?,?,?,?,?)').run(userId, 'PG Migration Fixture', null, 'P', now, `pg_stage_${process.pid}`, 'staging fixture');
  fixture.prepare('INSERT INTO stories(id,creator_id,title,category,created_at,status) VALUES(?,?,?,?,?,?)').run(storyId, userId, 'PG migration fixture post', 'test', now, 'draft');
  fixture.prepare('INSERT INTO albums(id,story_id,owner_id,slug,visibility,status,created_at,updated_at) VALUES(?,?,?,?,?,?,?,?)').run(albumId, storyId, userId, `pg-migration-fixture-${process.pid}`, 'private', 'draft', now, now);
  fixture.prepare('INSERT INTO album_media(id,album_id,storage_name,original_name,mime_type,byte_size,position,state,created_at) VALUES(?,?,?,?,?,?,?,?,?)').run(mediaId, albumId, `pg-migration-${process.pid}.jpg`, 'fixture.jpg', 'image/jpeg', 10, 0, 'ready', now);
  fixture.prepare('INSERT INTO media_pipeline(media_id,status,malware_status,processing_status,known_content_status,safety_status,moderation_status,attempts,updated_at) VALUES(?,?,?,?,?,?,?,?,?)').run(mediaId, 'QUARANTINED', 'BLOCKED', 'NOT_CONFIGURED', 'NOT_CONFIGURED', 'NOT_CONFIGURED', 'BLOCKED', 0, now);
  fixture.close();
  try {
    const child = spawnSync(process.execPath, ['scripts/postgres/migrate-staging.mjs', fixturePath], {
      cwd: root, encoding: 'utf8', env: { ...process.env, AROUSED_STAGING_DATABASE_URL: process.env.AROUSED_TEST_POSTGRES_URL, AROUSED_STAGING_DATABASE_NAME: process.env.AROUSED_TEST_POSTGRES_DATABASE_NAME, AROUSED_STAGING_DATABASE_ROLE: process.env.AROUSED_TEST_POSTGRES_DATABASE_ROLE, AROUSED_STAGING_DATABASE_DISPOSABLE: 'YES', AROUSED_ALLOW_STAGING_POSTGRES_MIGRATION: 'YES' },
      maxBuffer: 8 * 1024 * 1024,
    });
    assert.equal(child.status, 0, child.stderr || child.stdout);
    const result = JSON.parse(child.stdout);
    assert.equal(result.status, 'staging-import-verified');
    assert.equal(result.runtimeSwitched, false);
    assert.equal(result.tableCount, 31);
    assert.ok(result.constraintsVerified.uniqueIndexes > 0);
    assert.ok(result.constraintsVerified.foreignKeys > 0);
    for (const count of Object.values(result.counts)) assert.equal(count.sqlite, count.postgres);
    for (const count of Object.values(result.relationshipCounts)) assert.equal(count.sqlite, count.postgres);
    const { Pool } = await import('pg');
    const pool = new Pool({ connectionString: process.env.AROUSED_TEST_POSTGRES_URL, max: 1 });
    try {
      const preserved = await pool.query('SELECT a.owner_id,s.creator_id,m.id,m.storage_name,a.visibility,a.status,p.status AS moderation_status,p.malware_status FROM album_media m JOIN albums a ON a.id=m.album_id JOIN stories s ON s.id=a.story_id JOIN media_pipeline p ON p.media_id=m.id WHERE m.id=$1', [mediaId]);
      const row = preserved.rows[0];
      assert.deepEqual({ ...row, owner_id: Number(row.owner_id), creator_id: Number(row.creator_id), id: Number(row.id) }, { owner_id: userId, creator_id: userId, id: mediaId, storage_name: `pg-migration-${process.pid}.jpg`, visibility: 'private', status: 'draft', moderation_status: 'QUARANTINED', malware_status: 'BLOCKED' });
    } finally { await pool.end(); }
  } finally { await rm(scratch, { recursive: true, force: true }); }
});
